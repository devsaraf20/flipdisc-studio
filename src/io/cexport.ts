import type { Frame } from '../core/frame';

export type CLayout = 'rows' | 'columns';

export interface CExportOptions {
  name: string;
  /** rows: each row padded to whole bytes, MSB = leftmost.
   *  columns: each column padded to whole bytes, bit 0 = top (flip-disc style). */
  layout: CLayout;
  progmem: boolean;
  fps: number;
  /** per-frame durations in ms (optional; defaults to 1000/fps) */
  durations?: number[];
}

export function sanitizeIdent(s: string): string {
  const id = s.replace(/[^A-Za-z0-9_]/g, '_').replace(/^([0-9])/, '_$1');
  return id || 'frames';
}

export function encodeFrameBytes(f: Frame, layout: CLayout): Uint8Array {
  if (layout === 'rows') {
    const bpr = Math.ceil(f.width / 8);
    const out = new Uint8Array(bpr * f.height);
    for (let y = 0; y < f.height; y++)
      for (let x = 0; x < f.width; x++)
        if (f.data[y * f.width + x]) out[y * bpr + (x >> 3)] |= 0x80 >> (x & 7);
    return out;
  }
  const bpc = Math.ceil(f.height / 8);
  const out = new Uint8Array(bpc * f.width);
  for (let x = 0; x < f.width; x++)
    for (let y = 0; y < f.height; y++)
      if (f.data[y * f.width + x]) out[x * bpc + (y >> 3)] |= 1 << (y & 7);
  return out;
}

const hex = (b: number) => '0x' + b.toString(16).padStart(2, '0');

/** Produce a self-contained C/C++ header for Arduino or ESP32. */
export function exportCArray(frames: Frame[], o: CExportOptions): string {
  if (!frames.length) throw new Error('Nothing to export.');
  const { width, height } = frames[0];
  const id = sanitizeIdent(o.name);
  const ID = id.toUpperCase();
  const bytesPer = o.layout === 'rows' ? Math.ceil(width / 8) * height : Math.ceil(height / 8) * width;
  const pm = o.progmem ? ' PROGMEM' : '';
  const lines: string[] = [];
  lines.push('// Generated by Flip-Disc Studio');
  lines.push(`// ${frames.length} frame(s), ${width} x ${height} discs, ${bytesPer} bytes per frame`);
  if (o.layout === 'rows') {
    lines.push('// Layout: row-major. Each row is padded to whole bytes; MSB of each byte = leftmost disc.');
    lines.push(`// Disc (x, y) is on when: ${id}[f][y * ${ID}_BYTES_PER_ROW + x / 8] & (0x80 >> (x % 8))`);
  } else {
    lines.push('// Layout: column-major. Each column is padded to whole bytes; bit 0 = top disc.');
    lines.push(`// Disc (x, y) is on when: ${id}[f][x * ${ID}_BYTES_PER_COL + y / 8] & (1 << (y % 8))`);
  }
  lines.push('#pragma once');
  lines.push('#include <stdint.h>');
  if (o.progmem) {
    lines.push('#if defined(__AVR__)');
    lines.push('#include <avr/pgmspace.h>');
    lines.push('#elif !defined(PROGMEM)');
    lines.push('#define PROGMEM');
    lines.push('#endif');
  }
  lines.push('');
  lines.push(`#define ${ID}_WIDTH ${width}`);
  lines.push(`#define ${ID}_HEIGHT ${height}`);
  lines.push(`#define ${ID}_COUNT ${frames.length}`);
  lines.push(`#define ${ID}_FRAME_BYTES ${bytesPer}`);
  if (o.layout === 'rows') lines.push(`#define ${ID}_BYTES_PER_ROW ${Math.ceil(width / 8)}`);
  else lines.push(`#define ${ID}_BYTES_PER_COL ${Math.ceil(height / 8)}`);
  lines.push('');
  lines.push(`const uint8_t ${id}[${ID}_COUNT][${ID}_FRAME_BYTES]${pm} = {`);
  frames.forEach((f, i) => {
    const bytes = Array.from(encodeFrameBytes(f, o.layout)).map(hex);
    const rows: string[] = [];
    for (let k = 0; k < bytes.length; k += 16) rows.push('    ' + bytes.slice(k, k + 16).join(', '));
    lines.push(`  { // frame ${i}`);
    lines.push(rows.join(',\n'));
    lines.push(i < frames.length - 1 ? '  },' : '  }');
  });
  lines.push('};');
  lines.push('');
  const durs = frames.map((_, i) => Math.round(o.durations?.[i] ?? 1000 / Math.max(1, o.fps)));
  lines.push(`// How long to show each frame, in milliseconds.`);
  lines.push(`const uint16_t ${id}_ms[${ID}_COUNT]${pm} = { ${durs.join(', ')} };`);
  lines.push('');
  return lines.join('\n');
}

/** Merge consecutive identical frames, summing their durations (saves flash). */
export function dedupeFrames(frames: Frame[], frameMs: number): { frames: Frame[]; durations: number[] } {
  const outF: Frame[] = [];
  const outD: number[] = [];
  for (const f of frames) {
    const last = outF[outF.length - 1];
    if (last && last.data.every((v, i) => v === f.data[i])) outD[outD.length - 1] += frameMs;
    else {
      outF.push(f);
      outD.push(frameMs);
    }
  }
  return { frames: outF, durations: outD.map((d) => Math.min(65535, Math.round(d))) };
}
