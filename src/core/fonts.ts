const tinyCache = new Map<string, number[]>();
function tinyGlyph(ch: string): number[] {
  const key = TINY_ROWS[ch] !== undefined ? ch : TINY_ROWS[ch.toUpperCase()] !== undefined ? ch.toUpperCase() : '?';
  const cached = tinyCache.get(key);
  if (cached) return cached;
  const rows = TINY_ROWS[key].split(' ');
  const w = rows[0].length;
  const cols: number[] = [];
  for (let x = 0; x < w; x++) {
    let m = 0;
    rows.forEach((r, y) => {
      if (r[x] === '1') m |= 1 << y;
    });
    cols.push(m);
  }
  tinyCache.set(key, cols);
  return cols;
}

function boldGlyph(ch: string): number[] {
  const g = classicGlyph(ch);
  if (ch === ' ') return [0, 0, 0, 0];
  const out = [...g, 0];
  for (let i = out.length - 1; i > 0; i--) out[i] |= out[i - 1];
  return out;
}

export const FONTS: PixelFont[] = [
  { id: 'tiny', name: 'Tiny 3×5', height: 5, spacing: 1, lineGap: 1, glyph: tinyGlyph },
  { id: 'classic', name: 'Classic 5×7', height: 7, spacing: 1, lineGap: 1, glyph: classicGlyph },
  { id: 'bold', name: 'Bold 6×7', height: 7, spacing: 1, lineGap: 1, glyph: boldGlyph },
];

export function getFont(id: string): PixelFont {
  return FONTS.find((f) => f.id === id) ?? FONTS[1];
}

/** Rasterise one line of text to a column list (unscaled). */
export function lineColumns(font: PixelFont, text: string): number[] {
  const cols: number[] = [];
  const chars = Array.from(text);
  chars.forEach((ch, i) => {
    cols.push(...font.glyph(ch));
    if (i < chars.length - 1) for (let s = 0; s < font.spacing; s++) cols.push(0);
  });
  return cols;
}

export function measureLine(font: PixelFont, text: string, scale = 1): number {
  return lineColumns(font, text).length * scale;
}
