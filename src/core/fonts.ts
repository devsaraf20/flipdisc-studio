function classicGlyph(ch: string): number[] {
  let code = ch.charCodeAt(0);
  if (code === 0xb0) return [0x06, 0x09, 0x09, 0x06]; // degree sign
  if (code < 32 || code > 126) code = 63; // '?'
  const i = (code - 32) * 5;
  const cols = CLASSIC_5X7.slice(i, i + 5);
  // Trim empty columns on narrow glyphs (e.g. '!', 'i') for nicer proportional text.
  if (code === 32) return [0, 0, 0];
  let a = 0;
  let b = cols.length - 1;
  while (a < b && cols[a] === 0) a++;
  while (b > a && cols[b] === 0) b--;
  return cols.slice(a, b + 1);
}

