/**
 * Pixel fonts. Every glyph is stored as an array of columns, each column a
 * bit mask with bit 0 = top row. This is the same layout most flip-disc
 * controllers use (one byte per column), which keeps the mental model simple.
 */
export interface PixelFont {
  id: string;
  name: string;
  height: number;
  spacing: number;
  lineGap: number;
  glyph(ch: string): number[];
}

